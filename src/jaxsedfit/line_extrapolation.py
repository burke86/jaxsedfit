"""Continuum-anchored extrapolation of lines outside the fitted spectrum.

With ``agn.line_extrapolation_anchor = "continuum_ew"`` every broad and narrow
line that the spectrum does not cover receives

    L_line [W] = EW_rest [Angstrom] * L_lambda,AGN(lambda_line) [W / Angstrom],

where ``L_lambda,AGN`` is the unattenuated fitted AGN continuum, disc (bent
power law) plus torus dust emission, the counterpart of QSOGEN's power law plus
hot-dust blackbody against which its EWs are defined, and ``EW_rest`` comes
from the QSOGEN emission-line template
(Temple, Hewett & Banerji 2021; ``resources/templates/qsogen_line_ew.txt``,
generated by ``tools/generate_qsogen_line_ew.py``). The luminosities are
intrinsic, like the fitted-line anchor, and are attenuated, IGM-absorbed and
projected through the filters by the same downstream code.

QSOGEN changes the line strengths with luminosity (Baldwin effect) through
``emline_type = (M_i(z=2) - benorm) * beslope``. Here ``M_i(z=2)`` follows
from the disc ``L_nu`` at rest 2500 A with the Richards et al. (2006, eq. 4)
convention

    M_i(z=2) = -2.5 log10[L_nu(2500) / (4 pi (10 pc)^2)] - 48.60 - 2.5 log10(1 + 2),

with ``L_nu`` in erg s^-1 Hz^-1 and the 10 pc area in cm^2.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from importlib.resources import files

import jax
import jax.numpy as jnp
import numpy as np

LINE_EXTRAPOLATION_ANCHORS = ("fitted_lines", "continuum_ew")
DEFAULT_LINE_EXTRAPOLATION_ANCHOR = "fitted_lines"
LINE_EXTRAPOLATION_EW_SCOPES = ("blueward", "all")

QSOGEN_LINE_EW_RESOURCE = "resources/templates/qsogen_line_ew.txt"
QSOGEN_EMLINE_TYPE_MIN = -2.0
QSOGEN_EMLINE_TYPE_MAX = 3.0

_SPEED_OF_LIGHT_ANGSTROM_PER_S = 2.99792458e18
_WATT_TO_ERG_PER_S = 1.0e7
_TEN_PARSEC_CM = 3.0856775814913673e19
M_I_Z2_REFERENCE_WAVELENGTH_A = 2500.0
# M_i(z=2) = M_I_Z2_ZEROPOINT - 2.5 log10(L_nu(2500) / erg s^-1 Hz^-1).
M_I_Z2_ZEROPOINT = float(
    2.5 * np.log10(4.0 * np.pi * _TEN_PARSEC_CM**2) - 48.60 - 2.5 * np.log10(3.0)
)


def normalize_line_extrapolation_anchor(value) -> str:
    """Return the canonical anchor name or raise ``ValueError``."""
    anchor = str(value).strip().lower()
    if anchor not in LINE_EXTRAPOLATION_ANCHORS:
        allowed = ", ".join(repr(name) for name in LINE_EXTRAPOLATION_ANCHORS)
        raise ValueError(f"AGNConfig.line_extrapolation_anchor must be one of {allowed}; got {value!r}.")
    return anchor


def normalize_line_extrapolation_ew_scope(value) -> str:
    """Return the canonical continuum-EW scope or raise ``ValueError``."""
    scope = str(value).strip().lower()
    if scope not in LINE_EXTRAPOLATION_EW_SCOPES:
        allowed = ", ".join(repr(name) for name in LINE_EXTRAPOLATION_EW_SCOPES)
        raise ValueError(f"AGNConfig.line_extrapolation_ew_scope must be one of {allowed}; got {value!r}.")
    return scope


@dataclass(frozen=True)
class QsogenLineEWTable:
    """QSOGEN line-group equivalent widths on an ``emline_type`` grid."""

    names: tuple[str, ...]
    family: tuple[str, ...]
    window_lo: np.ndarray
    window_hi: np.ndarray
    emline_type_grid: np.ndarray
    ew_angstrom: np.ndarray
    beslope: float
    benorm: float


def _parse_header_value(lines, key):
    for line in lines:
        for part in line.lstrip("#").split(";"):
            name, sep, value = part.partition("=")
            if sep and name.strip() == key:
                return float(value.strip())
    raise ValueError(f"QSOGEN line table header lacks {key!r}.")


@lru_cache(maxsize=1)
def load_qsogen_line_ew_table() -> QsogenLineEWTable:
    """Load the vendored QSOGEN equivalent-width table."""
    text = files("jaxsedfit").joinpath(QSOGEN_LINE_EW_RESOURCE).read_text()
    header = [line for line in text.splitlines() if line.startswith("#")]
    grid_line = next(line for line in header if line.startswith("# emline_type_grid:"))
    grid = np.asarray(grid_line.split(":", 1)[1].split(), dtype=float)
    names, family, lo, hi, ew = [], [], [], [], []
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split()
        names.append(parts[0])
        family.append(parts[1])
        lo.append(float(parts[2]))
        hi.append(float(parts[3]))
        ew.append(np.asarray(parts[4:], dtype=float))
    ew = np.asarray(ew, dtype=float)
    if ew.shape != (len(names), grid.size):
        raise ValueError("QSOGEN line table rows do not match its emline_type grid.")
    return QsogenLineEWTable(
        names=tuple(names),
        family=tuple(family),
        window_lo=np.asarray(lo, dtype=float),
        window_hi=np.asarray(hi, dtype=float),
        emline_type_grid=grid,
        ew_angstrom=ew,
        beslope=_parse_header_value(header, "beslope"),
        benorm=_parse_header_value(header, "benorm"),
    )


def qsogen_line_ew_matrix(line_wave, line_weight, family: str = "broad") -> tuple[np.ndarray, np.ndarray]:
    """Map QSOGEN group EWs of one family ("broad" or "narrow") onto a jaxsedfit line list.

    A line belongs to a QSOGEN group of the family when its rest wavelength
    lies in the group's integration window and its template intensity in that
    family (``line_weight``) is positive. The group EW is shared among its
    member lines in proportion to those intensities (e.g. Ly-alpha and N V
    split the blended Ly-alpha + N V EW 10:3 for the default broad table).

    Returns
    -------
    ew_matrix : numpy.ndarray
        EW in Angstrom per line on the ``emline_type`` grid, shape
        ``(n_lines, n_grid)``; zero rows for lines without a QSOGEN group.
    anchored : numpy.ndarray
        Float mask, 1 for lines that received a QSOGEN EW.
    """
    table = load_qsogen_line_ew_table()
    wave = np.asarray(line_wave, dtype=float).reshape(-1)
    blagn = np.asarray(line_weight, dtype=float).reshape(-1)
    ew_matrix = np.zeros((wave.size, table.emline_type_grid.size), dtype=float)
    anchored = np.zeros(wave.size, dtype=float)
    for fam, lo, hi, ew in zip(table.family, table.window_lo, table.window_hi, table.ew_angstrom):
        if fam != family:
            continue
        members = (wave >= lo) & (wave < hi) & (blagn > 0.0)
        if not np.any(members):
            continue
        weights = blagn[members] / np.sum(blagn[members])
        ew_matrix[members] = weights[:, None] * ew[None, :]
        anchored[members] = 1.0
    return ew_matrix, anchored


def m_i_z2_from_disc_llambda_2500(llambda_2500_w_per_angstrom):
    """Return QSOGEN's ``M_i(z=2)`` from the disc ``L_lambda`` at rest 2500 A in W/A."""
    llambda = jnp.maximum(jnp.asarray(llambda_2500_w_per_angstrom, dtype=jnp.float64), 1.0e-300)
    lnu_erg_s_hz = (
        llambda
        * _WATT_TO_ERG_PER_S
        * M_I_Z2_REFERENCE_WAVELENGTH_A**2
        / _SPEED_OF_LIGHT_ANGSTROM_PER_S
    )
    return M_I_Z2_ZEROPOINT - 2.5 * jnp.log10(lnu_erg_s_hz)


def qsogen_emline_type(m_i_z2):
    """Return QSOGEN's Baldwin-effect ``emline_type`` for ``M_i(z=2)``, clipped as QSOGEN does."""
    table = load_qsogen_line_ew_table()
    value = (jnp.asarray(m_i_z2, dtype=jnp.float64) - table.benorm) * table.beslope
    return jnp.clip(value, QSOGEN_EMLINE_TYPE_MIN, QSOGEN_EMLINE_TYPE_MAX)


def _resolve_emline_type(disc_llambda_2500_w_per_angstrom, emline_type):
    if emline_type is None:
        return qsogen_emline_type(m_i_z2_from_disc_llambda_2500(disc_llambda_2500_w_per_angstrom))
    return jnp.clip(
        jnp.asarray(float(emline_type), dtype=jnp.float64),
        QSOGEN_EMLINE_TYPE_MIN,
        QSOGEN_EMLINE_TYPE_MAX,
    )


def _anchored_luminosity(line_wave, line_weight, family, continuum, disc_2500, emline_type):
    ew_matrix_np, anchored_np = qsogen_line_ew_matrix(line_wave, line_weight, family)
    table = load_qsogen_line_ew_table()
    grid = jnp.asarray(table.emline_type_grid, dtype=jnp.float64)
    emline_type = _resolve_emline_type(disc_2500, emline_type)
    ew_angstrom = jax.vmap(lambda row: jnp.interp(emline_type, grid, row))(jnp.asarray(ew_matrix_np, dtype=jnp.float64))
    continuum = jnp.clip(jnp.asarray(continuum, dtype=jnp.float64), 0.0, None)
    anchored = jnp.asarray(anchored_np, dtype=jnp.float64)
    return ew_angstrom * continuum * anchored, anchored, anchored_np


def continuum_ew_broad_line_luminosity(
    line_wave,
    line_blagn,
    agn_continuum_llambda_at_lines_w_per_angstrom,
    disc_llambda_2500_w_per_angstrom,
    emline_type=None,
):
    """Return intrinsic broad-line luminosities in W tied to the AGN continuum.

    Lines with a QSOGEN counterpart get ``EW * L_lambda,AGN(lambda_line)``.
    Lines without one keep their broad template ratio: they get
    ``line_blagn * sum(L_anchored) / sum(line_blagn_anchored)``, summed over
    all anchored lines regardless of spectral coverage.

    Parameters
    ----------
    line_wave, line_blagn : array-like
        Static rest wavelengths [A] and broad template intensities, shape (n_lines,).
    agn_continuum_llambda_at_lines_w_per_angstrom : jax.Array
        Unattenuated AGN continuum (disc + torus) ``L_lambda`` at ``line_wave``
        in W/A, shape (n_lines,).
    disc_llambda_2500_w_per_angstrom : jax.Array
        Unattenuated disc ``L_lambda`` at rest 2500 A in W/A (sets ``M_i(z=2)``).
    emline_type : float, optional
        Fixed QSOGEN ``emline_type``. ``None`` derives it from the disc luminosity.
    """
    anchored_lumin_w, anchored, anchored_np = _anchored_luminosity(
        line_wave, line_blagn, "broad", agn_continuum_llambda_at_lines_w_per_angstrom,
        disc_llambda_2500_w_per_angstrom, emline_type,
    )
    if not np.any(anchored_np):
        raise ValueError(
            "agn.line_extrapolation_anchor='continuum_ew' needs at least one broad line "
            "inside a QSOGEN line window; the emission-line template has none."
        )
    blagn = jnp.asarray(np.asarray(line_blagn, dtype=float).reshape(-1), dtype=jnp.float64)
    template_scale_w = jnp.sum(anchored_lumin_w) / jnp.maximum(jnp.sum(blagn * anchored), 1.0e-30)
    return jnp.where(anchored > 0.0, anchored_lumin_w, template_scale_w * blagn)


def continuum_ew_narrow_line_luminosity(
    line_wave,
    line_narrow_template,
    agn_continuum_llambda_at_lines_w_per_angstrom,
    disc_llambda_2500_w_per_angstrom,
    emline_type=None,
):
    """Return intrinsic narrow-line luminosities in W tied to the AGN continuum.

    Narrow lines inside a QSOGEN narrow window get ``EW * L_lambda,AGN``.
    QSOGEN has no narrow UV or near-IR lines (its broad Ly-alpha EW includes any
    core), so all other narrow lines get zero.
    """
    lumin, _anchored, _np = _anchored_luminosity(
        line_wave, line_narrow_template, "narrow", agn_continuum_llambda_at_lines_w_per_angstrom,
        disc_llambda_2500_w_per_angstrom, emline_type,
    )
    return lumin
